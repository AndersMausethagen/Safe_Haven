"""Generates "Safe Haven/Terrain (World)" from URP's Terrain Lit (run again after a URP upgrade):

    python AgentScripts/GenerateWorldTerrainShader.py

Copies Shaders/Terrain/TerrainLit.shader and TerrainLitPasses.hlsl from the installed URP package into
Assets/_Project/Shaders/Terrain/ and adds rock on steep ground: past a slope (with a ragged, noisy edge) the terrain
turns to a rock texture projected from three sides (triplanar), so cliffs never show stretched ground textures. The
rest of URP's terrain (layers, height blend, holes, instancing, base map, add pass) is unchanged.
"""
import glob
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
URP = glob.glob(os.path.join(ROOT, "Library", "PackageCache", "com.unity.render-pipelines.universal@*"))[0]
SOURCE = os.path.join(URP, "Shaders", "Terrain")
TARGET = os.path.join(ROOT, "Assets", "_Project", "Shaders", "Terrain")

HEADER = ("// GENERATED by AgentScripts/GenerateWorldTerrainShader.py from URP's {name}: do not edit by hand.\n"
          "// URP Terrain Lit plus rock on steep ground (triplanar), see Docs/LevelDesign.md \"Terrain shader\".\n")

PROPERTIES = """
        [Header(Rock on steep ground)]
        _CliffStrength("Rock on Steep Ground", Range(0, 1)) = 1
        _CliffSlopeStart("Rock Starts At (degrees)", Range(0, 90)) = 36
        _CliffSlopeEnd("Fully Rock At (degrees)", Range(0, 90)) = 52
        _CliffBreakup("Ragged Edge", Range(0, 1)) = 0.6
        [NoScaleOffset] _CliffAlbedo("Rock Colour", 2D) = "grey" {}
        [NoScaleOffset][Normal] _CliffNormal("Rock Normal", 2D) = "bump" {}
        [NoScaleOffset] _CliffMask("Rock Mask (R metallic, G occlusion, A smoothness)", 2D) = "white" {}
        _CliffTiling("Rock Size (metres)", Float) = 7
        _CliffTint("Rock Tint", Color) = (1, 1, 1, 1)
        _CliffNormalStrength("Rock Normal Strength", Range(0, 2)) = 1

"""

FUNCTIONS = """
// ---- Safe Haven: rock on steep ground -------------------------------------------------------------------------------
TEXTURE2D(_CliffAlbedo); SAMPLER(sampler_CliffAlbedo);
TEXTURE2D(_CliffNormal);
TEXTURE2D(_CliffMask);
float _CliffStrength, _CliffSlopeStart, _CliffSlopeEnd, _CliffBreakup, _CliffTiling, _CliffNormalStrength;
half4 _CliffTint;

// The terrain's own surface normal (without the layers' normal maps), for the slope.
half3 WorldGeometricNormal(Varyings IN)
{
#if defined(_NORMALMAP) && !defined(ENABLE_TERRAIN_PERPIXEL_NORMAL)
    return normalize(IN.normal.xyz);
#elif defined(ENABLE_TERRAIN_PERPIXEL_NORMAL)
    float2 sampleCoords = (IN.uvMainAndLM.xy / _TerrainHeightmapRecipSize.zw + 0.5f) * _TerrainHeightmapRecipSize.xy;
    return TransformObjectToWorldNormal(normalize(SAMPLE_TEXTURE2D(_TerrainNormalmapTexture, sampler_TerrainNormalmapTexture, sampleCoords).rgb * 2 - 1));
#else
    return normalize(IN.normal.xyz);
#endif
}

float WorldCliffHash(float3 p)
{
    p = frac(p * 0.3183099 + 0.1);
    p *= 17.0;
    return frac(p.x * p.y * p.z * (p.x + p.y + p.z));
}

float WorldCliffNoise(float3 p)
{
    float3 i = floor(p);
    float3 f = frac(p);
    f = f * f * (3.0 - 2.0 * f);
    return lerp(lerp(lerp(WorldCliffHash(i), WorldCliffHash(i + float3(1, 0, 0)), f.x),
                     lerp(WorldCliffHash(i + float3(0, 1, 0)), WorldCliffHash(i + float3(1, 1, 0)), f.x), f.y),
                lerp(lerp(WorldCliffHash(i + float3(0, 0, 1)), WorldCliffHash(i + float3(1, 0, 1)), f.x),
                     lerp(WorldCliffHash(i + float3(0, 1, 1)), WorldCliffHash(i + float3(1, 1, 1)), f.x), f.y), f.z);
}

// Past _CliffSlopeStart degrees the ground turns to rock projected from three sides (no stretching on cliffs), fully
// rock at _CliffSlopeEnd, with a noisy edge. Normals blend with the "whiteout" method.
void WorldCliffs(Varyings IN, inout InputData inputData, inout half3 albedo, inout half smoothness, inout half metallic, inout half occlusion)
{
    if (_CliffStrength <= 0)
    {
        return;
    }

    half3 n = WorldGeometricNormal(IN);
    float slope = degrees(acos(saturate(n.y)));
    float3 p = IN.positionWS;
    float noise = WorldCliffNoise(p * 0.35) * 0.65 + WorldCliffNoise(p * 1.1 + 7.3) * 0.35 - 0.5;
    half w = smoothstep(_CliffSlopeStart, max(_CliffSlopeEnd, _CliffSlopeStart + 0.1), slope + noise * _CliffBreakup * 26.0) * _CliffStrength;
    if (w <= 0.001)
    {
        return;
    }

    float3 q = p / max(_CliffTiling, 0.01);
    half3 blend = pow(abs(n), 4.0);
    blend /= max(dot(blend, 1.0), 1e-4);
    float2 uvX = q.zy;
    float2 uvY = q.xz;
    float2 uvZ = q.xy;
    half3 colour = (SAMPLE_TEXTURE2D(_CliffAlbedo, sampler_CliffAlbedo, uvX).rgb * blend.x +
                    SAMPLE_TEXTURE2D(_CliffAlbedo, sampler_CliffAlbedo, uvY).rgb * blend.y +
                    SAMPLE_TEXTURE2D(_CliffAlbedo, sampler_CliffAlbedo, uvZ).rgb * blend.z) * _CliffTint.rgb;
    half4 mask = SAMPLE_TEXTURE2D(_CliffMask, sampler_CliffAlbedo, uvX) * blend.x +
                 SAMPLE_TEXTURE2D(_CliffMask, sampler_CliffAlbedo, uvY) * blend.y +
                 SAMPLE_TEXTURE2D(_CliffMask, sampler_CliffAlbedo, uvZ) * blend.z;
    half3 tX = UnpackNormalScale(SAMPLE_TEXTURE2D(_CliffNormal, sampler_CliffAlbedo, uvX), _CliffNormalStrength);
    half3 tY = UnpackNormalScale(SAMPLE_TEXTURE2D(_CliffNormal, sampler_CliffAlbedo, uvY), _CliffNormalStrength);
    half3 tZ = UnpackNormalScale(SAMPLE_TEXTURE2D(_CliffNormal, sampler_CliffAlbedo, uvZ), _CliffNormalStrength);
    tX = half3(tX.xy + n.zy, abs(tX.z) * n.x);
    tY = half3(tY.xy + n.xz, abs(tY.z) * n.y);
    tZ = half3(tZ.xy + n.xy, abs(tZ.z) * n.z);
    half3 rockNormal = normalize(tX.zyx * blend.x + tY.xzy * blend.y + tZ.xyz * blend.z);

    albedo = lerp(albedo, colour, w);
    metallic = lerp(metallic, mask.r, w);
    occlusion = lerp(occlusion, mask.g, w);
    smoothness = lerp(smoothness, mask.a, w);
    inputData.normalWS = normalize(lerp(inputData.normalWS, rockNormal, w));
}
// ---------------------------------------------------------------------------------------------------------------------
"""

CALL = """
#ifndef TERRAIN_SPLAT_BASEPASS
    WorldCliffs(IN, inputData, albedo, smoothness, metallic, occlusion);
#endif
"""


def main():
    os.makedirs(TARGET, exist_ok=True)
    with open(os.path.join(SOURCE, "TerrainLit.shader"), encoding="utf-8") as f:
        shader = f.read()
    shader = shader.replace('Shader "Universal Render Pipeline/Terrain/Lit"', 'Shader "Safe Haven/Terrain (World)"', 1)
    shader = shader.replace("        [ToggleUI] _EnableInstancedPerPixelNormal", PROPERTIES + "        [ToggleUI] _EnableInstancedPerPixelNormal", 1)
    shader = shader.replace('#include "Packages/com.unity.render-pipelines.universal/Shaders/Terrain/TerrainLitPasses.hlsl"',
                            '#include "WorldTerrainLitPasses.hlsl"')
    shader = re.sub(r'\n\s*CustomEditor "[^"]+"\n', "\n", shader)  # Unity's terrain GUI hides the rock settings
    with open(os.path.join(TARGET, "WorldTerrainLit.shader"), "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER.format(name="TerrainLit.shader") + shader)

    with open(os.path.join(SOURCE, "TerrainLitPasses.hlsl"), encoding="utf-8") as f:
        passes = f.read()
    passes = passes.replace("UNIVERSAL_TERRAIN_LIT_PASSES_INCLUDED", "SAFE_HAVEN_WORLD_TERRAIN_LIT_PASSES_INCLUDED")
    anchor = passes.find("void InitializeInputData(")
    end = passes.find("\n}\n", anchor) + 3
    passes = passes[:end] + FUNCTIONS + passes[end:]
    setup = "    SetupTerrainDebugTextureData(inputData, IN.uvMainAndLM.xy);\n"
    assert setup in passes, "URP changed SplatmapFragment: update the generator"
    passes = passes.replace(setup, setup + CALL, 1)
    with open(os.path.join(TARGET, "WorldTerrainLitPasses.hlsl"), "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER.format(name="TerrainLitPasses.hlsl") + passes)
    print("generated", TARGET)


if __name__ == "__main__":
    main()
