# A generated raid's ground light field (GroundLight.hlsl, GroundLightMap): the canopy's and the land's shade on the ground, and
# light thrown back from sunlit ground. One texture array read with URP's shared linear-clamp sampler (the terrain is near its
# 64 textures and the four-layer pass at 14 of 16 samplers). The night's lift can take the factor above 1, which URP's occlusion
# would clamp away (GroundLightApply puts that part on bakedGI). Without a field (the Haven, the prologue) both lines change nothing.
GROUND_LIGHT = """    InitializeBakedGIData(IN, inputData);
    // A raid's ground light (GroundLight.hlsl): the canopy's and the land's shade (the night's lift on the indirect light), and light
    // thrown back from sunlit ground.
    GroundLightApply(GroundLightOnGround(IN.positionWS), occlusion, inputData.bakedGI);
    inputData.bakedGI += GroundLightBounce(IN.positionWS, inputData.normalWS);
"""

PASS_INCLUDE = 'Packages/com.unity.render-pipelines.universal/Shaders/Terrain/TerrainLitPasses.hlsl'
DEPTH_INCLUDE = 'Packages/com.unity.render-pipelines.universal/Shaders/Terrain/TerrainLitDepthNormalsPass.hlsl'


def tessellate_shader(shader):
    vertex_types = {
        "SplatmapVert": ("Attributes", "Varyings", "positionOS"),
        "ShadowPassVertex": ("AttributesLean", "VaryingsLean", "position"),
        "DepthOnlyVertex": ("AttributesLean", "VaryingsLean", "position"),
        "DepthNormalOnlyVertex": ("AttributesDepthNormal", "VaryingsDepthNormal", "positionOS"),
    }
    def transform(match):
        body = match.group(0)
        vertex = re.search(r"#pragma vertex (\w+)", body)
        if vertex is None or vertex.group(1) not in vertex_types:
            return body
        name = vertex.group(1)
        attributes, varyings, position = vertex_types[name]
        body = re.sub(r"#pragma target [\d.]+", "#pragma target 4.6", body)
        body = body.replace("#pragma vertex " + name,
                            "#pragma vertex WorldTessVertex\n            #pragma hull WorldHull\n            #pragma domain WorldDomain")
        # Shadow position/bias now runs in the domain stage, not only in the vertex stage.
        body = body.replace("#pragma multi_compile_vertex _ _CASTING_PUNCTUAL_LIGHT_SHADOW",
                            "#pragma multi_compile _ _CASTING_PUNCTUAL_LIGHT_SHADOW")
        body = body.replace(PASS_INCLUDE, "WorldTerrainLitPasses.hlsl").replace(DEPTH_INCLUDE, "WorldTerrainDepthNormals.hlsl")
        wrapper = (
            f'            #define WORLD_ATTRIBUTES {attributes}\n'
            f'            #define WORLD_VARYINGS {varyings}\n'
            f'            #define WORLD_POSITION {position}\n'
            f'            #define WORLD_VERTEX {name}\n'
            '            #include "WorldTerrainDomain.hlsl"\n            '
        )
        return re.sub(r"[ \t]+$", "", body.replace("ENDHLSL", wrapper + "ENDHLSL"), flags=re.M)
    return re.sub(r"HLSLPROGRAM.*?ENDHLSL", transform, shader, flags=re.S)


LAYER_UVS = ("uvSplat01.xy", "uvSplat01.zw", "uvSplat23.xy", "uvSplat23.zw")
CHANNELS = "rgba"


def replace_once(text, old, new, what):
    assert old in text, f"URP changed {what}: update the generator"
    return text.replace(old, new, 1)


def layer_sampling(passes):
    """Each layer sampled with anti-tiling and colour variation, and not at all where it has no weight."""
    for i, uv in enumerate(LAYER_UVS):
        c = CHANNELS[i]
        passes = replace_once(passes,
            f"nrm += splatControl.{c} * UnpackNormalScale(SAMPLE_TEXTURE2D(_Normal{i}, sampler_Normal0, {uv}), _NormalScale{i});",
            f"nrm += splatControl.{c} * WorldAntiTiledNormal(TEXTURE2D_ARGS(_Normal{i}, sampler_Normal0), {uv}, _NormalScale{i}, worldAntiTileBlend.{c}, splatControl.{c});",
            "NormalMapMix")
    albedo = "".join(f"    diffAlbedo[{i}] = SAMPLE_TEXTURE2D(_Splat{i}, sampler_Splat0, {uv});\n" for i, uv in enumerate(LAYER_UVS))
    blends = ", ".join(f"WorldAntiTileWeightIf({uv}, splatControl.{CHANNELS[i]})" for i, uv in enumerate(LAYER_UVS))
    sampled = "".join(f"    diffAlbedo[{i}] = WorldAntiTiledAlbedo(TEXTURE2D_ARGS(_Splat{i}, sampler_Splat0), {uv}, worldAntiTileBlend.{CHANNELS[i]}, splatControl.{CHANNELS[i]});\n"
                      for i, uv in enumerate(LAYER_UVS))
    shaded = "".join(f"        diffAlbedo[{i}].rgb = saturate(diffAlbedo[{i}].rgb * WorldMacroShadeIf({uv}, splatControl.{CHANNELS[i]}));\n"
                     for i, uv in enumerate(LAYER_UVS))
    passes = replace_once(passes, albedo,
        f"    worldAntiTileBlend = half4({blends});\n" + sampled +
        "    if (_MacroVariation > 0)\n    {\n"
        "        // Kept within 0..1: albedo brighter than white makes the lighting blow up, which bloom spreads over the screen.\n"
        + shaded + "    }\n",
        "SplatmapMix")

    passes = replace_once(passes,
        "void ComputeMasks(out half4 masks[4], half4 hasMask, float4 uvSplat01, float4 uvSplat23)",
        "void ComputeMasks(out half4 masks[4], half4 hasMask, float4 uvSplat01, float4 uvSplat23, half4 splatControl)",
        "ComputeMasks")
    masks = "".join(f"    masks[{i}] = lerp(masks[{i}], SAMPLE_TEXTURE2D(_Mask{i}, sampler_Mask0, {uv}), hasMask.{'xyzw'[i]});\n"
                    for i, uv in enumerate(LAYER_UVS))
    skipped = "".join(f"    [branch] if (splatControl.{CHANNELS[i]} > 0) masks[{i}] = lerp(masks[{i}], SAMPLE_TEXTURE2D_GRAD(_Mask{i}, sampler_Mask0, {uv}, dx{uv[7:9]}.{uv[-2:]}, dy{uv[7:9]}.{uv[-2:]}), hasMask.{'xyzw'[i]});\n"
                      for i, uv in enumerate(LAYER_UVS))
    passes = replace_once(passes, masks,
        "    // A layer without weight here never shows its mask (every use is multiplied by its weight): skip the read.\n"
        "    float4 dx01 = ddx(uvSplat01), dy01 = ddy(uvSplat01), dx23 = ddx(uvSplat23), dy23 = ddy(uvSplat23);\n" + skipped,
        "ComputeMasks body")

    # The masks now need the layer weights, so the control map is read first.
    control = ("    float2 splatUV = (IN.uvMainAndLM.xy * (_Control_TexelSize.zw - 1.0f) + 0.5f) * _Control_TexelSize.xy;\n"
               "    half4 splatControl = SAMPLE_TEXTURE2D(_Control, sampler_Control, splatUV);\n")
    passes = replace_once(passes,
        "    half4 masks[4];\n    ComputeMasks(masks, hasMask, IN.uvSplat01, IN.uvSplat23);\n\n" + control,
        control + "    half4 masks[4];\n    ComputeMasks(masks, hasMask, IN.uvSplat01, IN.uvSplat23, splatControl);\n",
        "SplatmapFragment")
    return passes


def single_pass_layers(passes):
    """Every painted layer in one pass (WorldTerrainAllLayers.hlsl, keyword _WORLD_ALL_LAYERS): TerrainSurface culls
    the add passes. URP's four-layer mix stays for the add passes and when the keyword is off."""
    fragment = "\n// Used in Standard Terrain shader\n#ifdef TERRAIN_GBUFFER\nGBufferFragOutput SplatmapFragment"
    passes = replace_once(passes, fragment,
        "\n#if defined(_WORLD_ALL_LAYERS) && !defined(TERRAIN_SPLAT_BASEPASS) && !defined(TERRAIN_SPLAT_ADDPASS)\n"
        "#include \"WorldTerrainAllLayers.hlsl\"\n#endif\n" + fragment, "the splatmap fragment")
    start = passes.index("void SplatmapFragment(")
    end = passes.index("    InputData inputData;", start)
    body = passes[start:end]
    body = replace_once(body, "#else\n\n    half4 hasMask",
        "#else\n\n    half3 albedo;\n    half smoothness, metallic, occlusion, alpha;\n    half4 splatControl = 0;\n"
        "#if defined(_WORLD_ALL_LAYERS) && !defined(TERRAIN_SPLAT_ADDPASS)\n"
        "    // Every painted layer in this one pass (WorldTerrainAllLayers.hlsl): the add passes are culled.\n"
        "    WorldAllLayersSurface(IN.uvMainAndLM.xy, albedo, smoothness, metallic, occlusion, normalTS, alpha);\n"
        "#else\n    {\n    half4 hasMask", "the splatmap fragment's layers")
    for declared in ("half4 splatControl = SAMPLE_TEXTURE2D", "half alpha = dot", "half3 albedo = mixedDiffuse",
                     "half smoothness = dot", "half metallic = dot"):
        body = replace_once(body, "    " + declared, "    " + declared.split(" ", 1)[1], "the splatmap fragment's " + declared)
    body = replace_once(body, "    half occlusion = dot(splatControl, defaultOcclusion);\n#endif\n",
        "    occlusion = dot(splatControl, defaultOcclusion);\n    }\n#endif\n#endif\n", "the splatmap fragment's occlusion")
    return passes[:start] + body + passes[end:]


def main():
    os.makedirs(TARGET, exist_ok=True)
    with open(os.path.join(SOURCE, "TerrainLit.shader"), encoding="utf-8") as f:
        shader = f.read()
