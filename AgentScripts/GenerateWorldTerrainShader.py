FUNCTIONS = """
// ---- Safe Haven: rock on steep ground -------------------------------------------------------------------------------
TEXTURE2D(_CliffAlbedo); SAMPLER(sampler_CliffAlbedo);
TEXTURE2D(_CliffNormal);
TEXTURE2D(_CliffMask);
float _CliffStrength, _CliffSlopeStart, _CliffSlopeEnd, _CliffBreakup, _CliffTiling, _CliffNormalStrength;
half4 _CliffTint;

// The terrain's own surface normal (without the layers' normal maps), for the slope.
half3 WorldGeometricNormal(Varyings IN)
{
#if defined(_NORMALMAP) && !defined(ENABLE_TERRAIN_PERPIXEL_NORMAL)
    return normalize(IN.normal.xyz);
#elif defined(ENABLE_TERRAIN_PERPIXEL_NORMAL)
    float2 sampleCoords = (IN.uvMainAndLM.xy / _TerrainHeightmapRecipSize.zw + 0.5f) * _TerrainHeightmapRecipSize.xy;
    return TransformObjectToWorldNormal(normalize(SAMPLE_TEXTURE2D(_TerrainNormalmapTexture, sampler_TerrainNormalmapTexture, sampleCoords).rgb * 2 - 1));
#else
    return normalize(IN.normal.xyz);
#endif
}

float WorldCliffHash(float3 p)
{
    p = frac(p * 0.3183099 + 0.1);
    p *= 17.0;
    return frac(p.x * p.y * p.z * (p.x + p.y + p.z));
}

float WorldCliffNoise(float3 p)
{
    float3 i = floor(p);
    float3 f = frac(p);
    f = f * f * (3.0 - 2.0 * f);
    return lerp(lerp(lerp(WorldCliffHash(i), WorldCliffHash(i + float3(1, 0, 0)), f.x),
                     lerp(WorldCliffHash(i + float3(0, 1, 0)), WorldCliffHash(i + float3(1, 1, 0)), f.x), f.y),
                lerp(lerp(WorldCliffHash(i + float3(0, 0, 1)), WorldCliffHash(i + float3(1, 0, 1)), f.x),
                     lerp(WorldCliffHash(i + float3(0, 1, 1)), WorldCliffHash(i + float3(1, 1, 1)), f.x), f.y), f.z);
}

// Past _CliffSlopeStart degrees the ground turns to rock projected from three sides (no stretching on cliffs), fully
// rock at _CliffSlopeEnd, with a noisy edge. Normals blend with the "whiteout" method.
void WorldCliffs(Varyings IN, inout InputData inputData, inout half3 albedo, inout half smoothness, inout half metallic, inout half occlusion)
{
    if (_CliffStrength <= 0)
    {
        return;
    }

    half3 n = WorldGeometricNormal(IN);
    float slope = degrees(acos(saturate(n.y)));
    float3 p = IN.positionWS;
    float noise = WorldCliffNoise(p * 0.35) * 0.65 + WorldCliffNoise(p * 1.1 + 7.3) * 0.35 - 0.5;
    half w = smoothstep(_CliffSlopeStart, max(_CliffSlopeEnd, _CliffSlopeStart + 0.1), slope + noise * _CliffBreakup * 26.0) * _CliffStrength;
    if (w <= 0.001)
    {
        return;
    }

    float3 q = p / max(_CliffTiling, 0.01);
    half3 blend = pow(abs(n), 4.0);
    blend /= max(dot(blend, 1.0), 1e-4);
    float2 uvX = q.zy;
    float2 uvY = q.xz;
    float2 uvZ = q.xy;
    half3 colour = (SAMPLE_TEXTURE2D(_CliffAlbedo, sampler_CliffAlbedo, uvX).rgb * blend.x +
                    SAMPLE_TEXTURE2D(_CliffAlbedo, sampler_CliffAlbedo, uvY).rgb * blend.y +
                    SAMPLE_TEXTURE2D(_CliffAlbedo, sampler_CliffAlbedo, uvZ).rgb * blend.z) * _CliffTint.rgb;
    half4 mask = SAMPLE_TEXTURE2D(_CliffMask, sampler_CliffAlbedo, uvX) * blend.x +
                 SAMPLE_TEXTURE2D(_CliffMask, sampler_CliffAlbedo, uvY) * blend.y +
                 SAMPLE_TEXTURE2D(_CliffMask, sampler_CliffAlbedo, uvZ) * blend.z;
    half3 tX = UnpackNormalScale(SAMPLE_TEXTURE2D(_CliffNormal, sampler_CliffAlbedo, uvX), _CliffNormalStrength);
    half3 tY = UnpackNormalScale(SAMPLE_TEXTURE2D(_CliffNormal, sampler_CliffAlbedo, uvY), _CliffNormalStrength);
    half3 tZ = UnpackNormalScale(SAMPLE_TEXTURE2D(_CliffNormal, sampler_CliffAlbedo, uvZ), _CliffNormalStrength);
    tX = half3(tX.xy + n.zy, abs(tX.z) * n.x);
    tY = half3(tY.xy + n.xz, abs(tY.z) * n.y);
    tZ = half3(tZ.xy + n.xy, abs(tZ.z) * n.z);
    half3 rockNormal = normalize(tX.zyx * blend.x + tY.xzy * blend.y + tZ.xyz * blend.z);

    albedo = lerp(albedo, colour, w);
    metallic = lerp(metallic, mask.r, w);
    occlusion = lerp(occlusion, mask.g, w);
    smoothness = lerp(smoothness, mask.a, w);
    inputData.normalWS = normalize(lerp(inputData.normalWS, rockNormal, w));
}

// Rain on the ground (WeatherSystem sets the wetness). Soaked ground is darker and shinier everywhere it is level enough
// to hold water; puddles fill in the low spots of a noise that stays put, growing with the wetness, and ring under the rain.
float _SafeHavenWetness, _SafeHavenRain;

float WorldWetHash(float2 p)
{
    p = frac(p * float2(123.34, 456.21));
    p += dot(p, p + 45.32);
    return frac(p.x * p.y);
}

float WorldWetNoise(float2 p)
{
    float2 cell = floor(p);
    float2 f = frac(p);
    f = f * f * (3.0 - 2.0 * f);
    return lerp(lerp(WorldWetHash(cell), WorldWetHash(cell + float2(1, 0)), f.x),
                lerp(WorldWetHash(cell + float2(0, 1)), WorldWetHash(cell + float2(1, 1)), f.x), f.y);
}

// How much a raindrop's ring leans the surface here: expanding rings, one to a cell, each with its own moment.
float2 WorldRainRings(float2 p, float time)
{
    float2 cell = floor(p);
    float2 offset = frac(p) - 0.5;
    float seed = WorldWetHash(cell);
    float age = frac(time * 0.9 + seed);
    offset -= (float2(seed, frac(seed * 7.13)) - 0.5) * 0.4;
    float radius = length(offset);
    float wave = sin((radius - age * 0.45) * 42.0) * saturate(1.0 - abs(radius - age * 0.45) * 9.0) * (1.0 - age);
    return radius > 0.001 ? offset / radius * wave : 0;
}

void WorldWetness(Varyings IN, inout InputData inputData, inout half3 albedo, inout half smoothness, inout half metallic, inout half occlusion, out half skySheen)
{
    skySheen = 0;
    half wetness = _SafeHavenWetness;
    if (wetness <= 0.001)
    {
        return;
    }

    // Wide on purpose: terrain normals change from triangle to triangle, and a narrow range draws those triangles.
    half level = smoothstep(0.62, 0.8, WorldGeometricNormal(IN).y);
    half soaked = wetness * (0.5 + 0.5 * level);
    albedo *= 1.0 - 0.34 * soaked;
    smoothness = lerp(smoothness, max(smoothness, 0.62), soaked);

    float2 xz = IN.positionWS.xz;
    float lows = WorldWetNoise(xz * 0.75) * 0.55 + WorldWetNoise(xz * 2.1 + 17.3) * 0.3 + WorldWetNoise(xz * 5.3 + 41.7) * 0.15;
    float shore = lerp(0.76, 0.63, wetness);
    half puddle = smoothstep(shore, shore + 0.05, lows) * level * saturate(wetness * 3.0);
    if (puddle <= 0.001)
    {
        return;
    }

    albedo = lerp(albedo, albedo * 0.6, puddle);
    smoothness = lerp(smoothness, 0.97, puddle);
    metallic = lerp(metallic, 0.2, puddle);
    occlusion = lerp(occlusion, 1.0, puddle);
    float2 lean = _SafeHavenRain * (WorldRainRings(xz * 1.9, _Time.y) + WorldRainRings(xz * 1.9 + 3.7, _Time.y * 1.3 + 0.5)) * 0.32;
    inputData.normalWS = normalize(lerp(inputData.normalWS, normalize(half3(lean.x, 1.0, lean.y)), puddle));

    // Water shows the sky, and more of it the flatter it is seen. There are no reflections of the scene to draw on, so
    // the sky's ambient colour stands in; black puddles read as holes.
    half facing = saturate(dot(inputData.normalWS, inputData.viewDirectionWS));
    skySheen = puddle * lerp(0.26, 0.05, facing * facing);
}
// ---------------------------------------------------------------------------------------------------------------------
"""

CALL = """
    inputData.normalWS = WorldSurfaceNormal(IN.uvMainAndLM.xy, IN.positionWS,
        WorldGeometricNormal(IN), inputData.normalWS);
    float footprintMask = WorldFootprintMask(IN.positionWS.xz);
    if (footprintMask > 0)
    {
        float response;
        WorldDisplacementHeightLOD(IN.uvMainAndLM.xy, _DisplacementMip, response);
        float compression = saturate(footprintMask * 4) * response * _FootprintSettings.y;
        #ifdef TERRAIN_SPLAT_BASEPASS
            half3 compressedAlbedo = SAMPLE_TEXTURE2D_LOD(_MainTex, sampler_MainTex, IN.uvMainAndLM.xy, 2).rgb;
        #else
            half3 compressedAlbedo = SAMPLE_TEXTURE2D_LOD(_Splat0, sampler_Splat0, IN.uvSplat01.xy, 5).rgb * _DiffuseRemapScale0.rgb * splatControl.r;
            compressedAlbedo += SAMPLE_TEXTURE2D_LOD(_Splat1, sampler_Splat0, IN.uvSplat01.zw, 5).rgb * _DiffuseRemapScale1.rgb * splatControl.g;
            compressedAlbedo += SAMPLE_TEXTURE2D_LOD(_Splat2, sampler_Splat0, IN.uvSplat23.xy, 5).rgb * _DiffuseRemapScale2.rgb * splatControl.b;
            compressedAlbedo += SAMPLE_TEXTURE2D_LOD(_Splat3, sampler_Splat0, IN.uvSplat23.zw, 5).rgb * _DiffuseRemapScale3.rgb * splatControl.a;
        #endif
        albedo = lerp(albedo, compressedAlbedo, saturate(compression));
        albedo *= 1 - saturate(footprintMask * response * _FootprintDarkening);
    }
    occlusion = saturate(1 - (1 - occlusion) * _SurfaceOcclusion);
    smoothness = saturate(smoothness * _SurfaceSmoothness);
#ifndef TERRAIN_SPLAT_BASEPASS
    WorldCliffs(IN, inputData, albedo, smoothness, metallic, occlusion);
#endif
    half skySheen;
    WorldWetness(IN, inputData, albedo, smoothness, metallic, occlusion, skySheen);
"""


PASS_INCLUDE = 'Packages/com.unity.render-pipelines.universal/Shaders/Terrain/TerrainLitPasses.hlsl'
DEPTH_INCLUDE = 'Packages/com.unity.render-pipelines.universal/Shaders/Terrain/TerrainLitDepthNormalsPass.hlsl'


def tessellate_shader(shader):
    vertex_types = {
        "SplatmapVert": ("Attributes", "Varyings", "positionOS"),
        "ShadowPassVertex": ("AttributesLean", "VaryingsLean", "position"),
        "DepthOnlyVertex": ("AttributesLean", "VaryingsLean", "position"),
        "DepthNormalOnlyVertex": ("AttributesDepthNormal", "VaryingsDepthNormal", "positionOS"),
    }
    def transform(match):
        body = match.group(0)
        vertex = re.search(r"#pragma vertex (\w+)", body)
        if vertex is None or vertex.group(1) not in vertex_types:
            return body
        name = vertex.group(1)
        attributes, varyings, position = vertex_types[name]
        body = re.sub(r"#pragma target [\d.]+", "#pragma target 4.6", body)
        body = body.replace("#pragma vertex " + name,
                            "#pragma vertex WorldTessVertex\n            #pragma hull WorldHull\n            #pragma domain WorldDomain")
        # Shadow position/bias now runs in the domain stage, not only in the vertex stage.
        body = body.replace("#pragma multi_compile_vertex _ _CASTING_PUNCTUAL_LIGHT_SHADOW",
                            "#pragma multi_compile _ _CASTING_PUNCTUAL_LIGHT_SHADOW")
        body = body.replace(PASS_INCLUDE, "WorldTerrainLitPasses.hlsl").replace(DEPTH_INCLUDE, "WorldTerrainDepthNormals.hlsl")
        wrapper = (
            f'            #define WORLD_ATTRIBUTES {attributes}\n'
            f'            #define WORLD_VARYINGS {varyings}\n'
            f'            #define WORLD_POSITION {position}\n'
            f'            #define WORLD_VERTEX {name}\n'
            '            #include "WorldTerrainDomain.hlsl"\n            '
        )
        return re.sub(r"[ \t]+$", "", body.replace("ENDHLSL", wrapper + "ENDHLSL"), flags=re.M)
    return re.sub(r"HLSLPROGRAM.*?ENDHLSL", transform, shader, flags=re.S)


def main():
    os.makedirs(TARGET, exist_ok=True)
    with open(os.path.join(SOURCE, "TerrainLit.shader"), encoding="utf-8") as f:
        shader = f.read()
    shader = shader.replace('Shader "Universal Render Pipeline/Terrain/Lit"', 'Shader "Safe Haven/Terrain (World)"', 1)
    shader = shader.replace("        [ToggleUI] _EnableInstancedPerPixelNormal", PROPERTIES + "        [ToggleUI] _EnableInstancedPerPixelNormal", 1)
    shader = tessellate_shader(shader)
    shader = shader.replace("Hidden/Universal Render Pipeline/Terrain/Lit (Add Pass)", "Hidden/Safe Haven/Terrain/Add")
    shader = shader.replace("Hidden/Universal Render Pipeline/Terrain/Lit (Base Pass)", "Hidden/Safe Haven/Terrain/Base")
    shader = re.sub(r'\n\s*CustomEditor "[^"]+"\n', "\n", shader)  # Unity's terrain GUI hides the rock settings
    with open(os.path.join(TARGET, "WorldTerrainLit.shader"), "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER.format(name="TerrainLit.shader") + shader)

    with open(os.path.join(SOURCE, "TerrainLitPasses.hlsl"), encoding="utf-8") as f:
        passes = f.read()
    passes = passes.replace("UNIVERSAL_TERRAIN_LIT_PASSES_INCLUDED", "SAFE_HAVEN_WORLD_TERRAIN_LIT_PASSES_INCLUDED")
    # Instancing is resolved once in the control vertex, before interpolation by the domain shader.
    passes = re.sub(r"    TerrainInstancing\([^;]+;\n", "", passes)
    anchor = passes.index("struct Varyings")
    passes = passes[:anchor] + '#include "WorldTerrainDisplacement.hlsl"\n\n' + passes[anchor:]
    anchor = passes.find("void InitializeInputData(")
    end = passes.find("\n}\n", anchor) + 3
    passes = passes[:end] + FUNCTIONS + passes[end:]
    passes = passes.replace("mixedNormal = normalize(nrm.xyz);",
                            "nrm.xy *= _NormalMapStrength;\n        mixedNormal = normalize(nrm.xyz);")
    setup = "    SetupTerrainDebugTextureData(inputData, IN.uvMainAndLM.xy);\n"
    assert setup in passes, "URP changed SplatmapFragment: update the generator"
    passes = passes.replace(setup, setup + CALL, 1)
    forward = "/* emission */ half3(0, 0, 0), alpha);"
    assert forward in passes, "URP changed the forward lighting call: update the generator"
    passes = passes.replace(forward, "/* emission */ skySheen * SampleSH(half3(0, 1, 0)), alpha);", 1)
    gbuffer = "    color.a = alpha;\n    SplatmapFinalColor(color, inputData.fogCoord);\n\n    // Dynamic lighting"
    assert gbuffer in passes, "URP changed the gbuffer lighting: update the generator"
    passes = passes.replace(gbuffer, "    color.rgb += skySheen * SampleSH(half3(0, 1, 0));\n" + gbuffer, 1)
    debug_anchor = "    outColor = half4(color.rgb, 1.0h);"
    assert debug_anchor in passes, "URP changed forward output: update the generator"
    passes = passes.replace(debug_anchor, debug_anchor + """
    if (_SurfaceDebug > 0.5)
    {
        float footprintResponse;
        WorldDisplacementHeightLOD(IN.uvMainAndLM.xy, _DisplacementMip, footprintResponse);
        half3 preview = _SurfaceDebug < 1.5
            ? (WorldDisplacementHeight(IN.uvMainAndLM.xy) + 0.5).xxx
            : _SurfaceDebug < 2.5 ? inputData.normalWS * 0.5 + 0.5
            : (WorldFootprintMask(IN.positionWS.xz) * footprintResponse).xxx;
        outColor.rgb = preview;
        #ifdef TERRAIN_SPLAT_ADDPASS
            outColor.rgb = 0;
        #endif
    }
""")
    with open(os.path.join(TARGET, "WorldTerrainLitPasses.hlsl"), "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER.format(name="TerrainLitPasses.hlsl") + passes)
    with open(os.path.join(SOURCE, "TerrainLitDepthNormalsPass.hlsl"), encoding="utf-8") as f:
        depth = f.read().replace(PASS_INCLUDE, "WorldTerrainLitPasses.hlsl")
    depth = re.sub(r"    TerrainInstancing\([^;]+;\n", "", depth)
    depth = depth.replace("    float4 clipPos", "    float3 positionWS : TEXCOORD6;\n    float4 clipPos", 1)
    depth = depth.replace("    o.clipPos = attributes.positionCS;", "    o.clipPos = attributes.positionCS;\n    o.positionWS = attributes.positionWS;")
    # Resolve URP's instanced branch to a distinct geometric normal for consistent height-normal composition.
    depth = depth.replace("        half3 viewDirWS = IN.viewDir;\n", "")
    depth = depth.replace("half3 normalWS = TransformObjectToWorldNormal", "half3 terrainNormalWS = TransformObjectToWorldNormal")
    depth = depth.replace("cross(GetObjectToWorldMatrix()._13_23_33, normalWS)", "cross(GetObjectToWorldMatrix()._13_23_33, terrainNormalWS)")
    depth = depth.replace("cross(normalWS, tangentWS), normalWS", "cross(terrainNormalWS, tangentWS), terrainNormalWS")
    normal_anchor = "    #if defined(_GBUFFER_NORMALS_OCT)"
    depth = depth.replace(normal_anchor, """
    float3 baseNormalWS = normalize(IN.normal.xyz);
    #if defined(ENABLE_TERRAIN_PERPIXEL_NORMAL)
        baseNormalWS = terrainNormalWS;
    #endif
    normalWS = WorldSurfaceNormal(IN.uvMainAndLM.xy, IN.positionWS, baseNormalWS, normalize(normalWS));

""" + normal_anchor, 1)
    depth = depth.replace("outNormalWS.a = smoothness;", "outNormalWS.a = saturate(smoothness * _SurfaceSmoothness);")
    with open(os.path.join(TARGET, "WorldTerrainDepthNormals.hlsl"), "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER.format(name="TerrainLitDepthNormalsPass.hlsl") + depth)
    for source_name, target_name, shader_name in (
        ("TerrainLitAdd.shader", "WorldTerrainAdd.shader", "Hidden/Safe Haven/Terrain/Add"),
        ("TerrainLitBase.shader", "WorldTerrainBase.shader", "Hidden/Safe Haven/Terrain/Base"),
    ):
        with open(os.path.join(SOURCE, source_name), encoding="utf-8") as f:
            extra = f.read()
        extra = re.sub(r'Shader "[^"]+"', f'Shader "{shader_name}"', extra, count=1)
        extra = extra.replace("    Properties\n    {", "    Properties\n    {\n" + PROPERTIES, 1)
        extra = tessellate_shader(extra)
        with open(os.path.join(TARGET, target_name), "w", encoding="utf-8", newline="\n") as f:
            f.write(HEADER.format(name=source_name) + extra)
    print("generated", TARGET)


if __name__ == "__main__":
    main()
