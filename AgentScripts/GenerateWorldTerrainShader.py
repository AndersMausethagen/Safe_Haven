FUNCTIONS = """
// ---- Safe Haven: rock on steep ground -------------------------------------------------------------------------------
// Its textures and settings are declared in WorldTerrainDisplacement.hlsl: the domain stage pushes the rock out too.

// The terrain's own surface normal (without the layers' normal maps), for the slope.
half3 WorldGeometricNormal(Varyings IN)
{
#if defined(_NORMALMAP) && !defined(ENABLE_TERRAIN_PERPIXEL_NORMAL)
    return normalize(IN.normal.xyz);
#elif defined(ENABLE_TERRAIN_PERPIXEL_NORMAL)
    float2 sampleCoords = (IN.uvMainAndLM.xy / _TerrainHeightmapRecipSize.zw + 0.5f) * _TerrainHeightmapRecipSize.xy;
    return TransformObjectToWorldNormal(normalize(SAMPLE_TEXTURE2D(_TerrainNormalmapTexture, sampler_TerrainNormalmapTexture, sampleCoords).rgb * 2 - 1));
#else
    return normalize(IN.normal.xyz);
#endif
}

float WorldCliffHash(float3 p)
{
    p = frac(p * 0.3183099 + 0.1);
    p *= 17.0;
    return frac(p.x * p.y * p.z * (p.x + p.y + p.z));
}

float WorldCliffNoise(float3 p)
{
    float3 i = floor(p);
    float3 f = frac(p);
    f = f * f * (3.0 - 2.0 * f);
    return lerp(lerp(lerp(WorldCliffHash(i), WorldCliffHash(i + float3(1, 0, 0)), f.x),
                     lerp(WorldCliffHash(i + float3(0, 1, 0)), WorldCliffHash(i + float3(1, 1, 0)), f.x), f.y),
                lerp(lerp(WorldCliffHash(i + float3(0, 0, 1)), WorldCliffHash(i + float3(1, 0, 1)), f.x),
                     lerp(WorldCliffHash(i + float3(0, 1, 1)), WorldCliffHash(i + float3(1, 1, 1)), f.x), f.y), f.z);
}

// ---- Safe Haven: hiding the layers' repetition ----------------------------------------------------------------------
// Each layer is sampled twice: as painted, and turned and scaled. Slow noise in that layer's own UVs picks between them,
// so no tile repeats the same way twice, and a broader noise shifts its brightness the way real ground varies.
float _AntiTiling, _AntiTilingScale, _MacroVariation;
static half4 worldAntiTileBlend;
static const float2x2 WorldAntiTileTurn = float2x2(0.4536, -0.8912, 0.8912, 0.4536); // 63 degrees

float2 WorldAntiTileUV(float2 uv) { return mul(WorldAntiTileTurn, uv) * _AntiTilingScale + float2(0.37, 0.71); }

half WorldAntiTileWeight(float2 uv)
{
    if (_AntiTiling <= 0) return 0;
    float n = WorldCliffNoise(float3(uv * 0.23, 3.1)) * 0.7 + WorldCliffNoise(float3(uv * 0.61, 9.7)) * 0.3;
    return smoothstep(0.3, 0.7, n) * _AntiTiling;
}

half WorldMacroShade(float2 uv)
{
    return 1.0 + (WorldCliffNoise(float3(uv * 0.07, 17.3)) - 0.5) * 2.0 * _MacroVariation;
}

// Layers with no weight at a pixel are skipped entirely: no texture reads, no noise. Their contribution is multiplied by
// that zero weight anyway, so the image is unchanged. Derivatives are taken before branching, as dynamic branches can't
// give implicit ones.
half4 WorldAntiTiledAlbedo(TEXTURE2D_PARAM(tex, smp), float2 uv, half blend, half weight)
{
    float2 dx = ddx(uv), dy = ddy(uv);
    [branch] if (weight <= 0) return 0;
    half4 a = SAMPLE_TEXTURE2D_GRAD(tex, smp, uv, dx, dy);
    [branch] if (blend <= 0.001) return a;
    float2x2 turn = WorldAntiTileTurn * _AntiTilingScale;
    return lerp(a, SAMPLE_TEXTURE2D_GRAD(tex, smp, WorldAntiTileUV(uv), mul(turn, dx), mul(turn, dy)), blend);
}

half3 WorldAntiTiledNormal(TEXTURE2D_PARAM(tex, smp), float2 uv, half scale, half blend, half weight)
{
    float2 dx = ddx(uv), dy = ddy(uv);
    [branch] if (weight <= 0) return 0;
    half3 a = UnpackNormalScale(SAMPLE_TEXTURE2D_GRAD(tex, smp, uv, dx, dy), scale);
    [branch] if (blend <= 0.001) return a;
    float2x2 turn = WorldAntiTileTurn * _AntiTilingScale;
    half3 b = UnpackNormalScale(SAMPLE_TEXTURE2D_GRAD(tex, smp, WorldAntiTileUV(uv), mul(turn, dx), mul(turn, dy)), scale);
    b.xy = mul(transpose(WorldAntiTileTurn), b.xy); // back into the terrain's tangent frame
    // Not normalized here (two opposed samples could mix to zero length, and normalize(0) is NaN): NormalMapMix
    // normalizes the layers' sum, with its own guard.
    return lerp(a, b, blend);
}

half WorldAntiTileWeightIf(float2 uv, half weight)
{
    [branch] if (weight <= 0) return 0;
    return WorldAntiTileWeight(uv);
}

half WorldMacroShadeIf(float2 uv, half weight)
{
    [branch] if (weight <= 0) return 1;
    return WorldMacroShade(uv);
}

// One projection of the rock: sampled as it is and, where WorldRockBlend says, turned (WorldTerrainDisplacement.hlsl).
void WorldRockSample(TEXTURE2D_PARAM(colourMap, smp), TEXTURE2D_PARAM(normalMap, normalSmp), TEXTURE2D_PARAM(maskMap, maskSmp),
                     float2 uv, half b, half normalStrength, out half3 colour, out half4 mask, out half3 normal)
{
    colour = SAMPLE_TEXTURE2D(colourMap, smp, uv).rgb;
    mask = SAMPLE_TEXTURE2D(maskMap, maskSmp, uv);
    normal = UnpackNormalScale(SAMPLE_TEXTURE2D(normalMap, normalSmp, uv), normalStrength);
    [branch] if (b > 0.001)
    {
        float2 turned = WorldRockTurnedUV(uv);
        half3 turnedNormal = UnpackNormalScale(SAMPLE_TEXTURE2D(normalMap, normalSmp, turned), normalStrength);
        turnedNormal.xy = mul(transpose(WorldRockTurn), turnedNormal.xy); // back into this projection's frame
        colour = lerp(colour, SAMPLE_TEXTURE2D(colourMap, smp, turned).rgb, b);
        mask = lerp(mask, SAMPLE_TEXTURE2D(maskMap, maskSmp, turned), b);
        normal = normalize(lerp(normal, turnedNormal, b));
    }
}

// Rock projected from three sides (no stretching on cliffs). Normals blend with the "whiteout" method.
void WorldTriplanarRock(TEXTURE2D_PARAM(colourMap, smp), TEXTURE2D_PARAM(normalMap, normalSmp), TEXTURE2D_PARAM(maskMap, maskSmp),
                        float3 p, half3 n, half3 blend, float tiling, half3 tint, half normalStrength,
                        out half3 colour, out half4 mask, out half3 normal)
{
    float3 q = p / max(tiling, 0.01);
    half b = WorldRockBlend(q);
    half3 cX, cY, cZ, tX, tY, tZ;
    half4 mX, mY, mZ;
    WorldRockSample(TEXTURE2D_ARGS(colourMap, smp), TEXTURE2D_ARGS(normalMap, normalSmp), TEXTURE2D_ARGS(maskMap, maskSmp), q.zy, b, normalStrength, cX, mX, tX);
    WorldRockSample(TEXTURE2D_ARGS(colourMap, smp), TEXTURE2D_ARGS(normalMap, normalSmp), TEXTURE2D_ARGS(maskMap, maskSmp), q.xz, b, normalStrength, cY, mY, tY);
    WorldRockSample(TEXTURE2D_ARGS(colourMap, smp), TEXTURE2D_ARGS(normalMap, normalSmp), TEXTURE2D_ARGS(maskMap, maskSmp), q.xy, b, normalStrength, cZ, mZ, tZ);
    colour = (cX * blend.x + cY * blend.y + cZ * blend.z) * tint;
    mask = mX * blend.x + mY * blend.y + mZ * blend.z;
    tX = half3(tX.xy + n.zy, abs(tX.z) * n.x);
    tY = half3(tY.xy + n.xz, abs(tY.z) * n.y);
    tZ = half3(tZ.xy + n.xy, abs(tZ.z) * n.z);
    normal = normalize(tX.zyx * blend.x + tY.xzy * blend.y + tZ.xyz * blend.z);
}

// Layered rock (2026-11-18, the user's cliff-edge reference): on faces steeper than Beds From, the rock steps in horizontal beds by
// world height, each bed a shade of its own, the lines bent by broad noise so they wander along a wall, with a dark seam under each
// bed's lip where the softer layer below has worn back. Off at 0 (every terrain but those that ask for it).
void WorldStrata(float3 p, float slope, inout half3 colour, inout half4 mask)
{
    if (_StrataStrength <= 0)
    {
        return;
    }

    half face = saturate((slope - _StrataSlope) / 14.0);
    if (face <= 0.001)
    {
        return;
    }

    // The beds' lines wander: broadly along a wall (a few metres up and down) and a little at arm's length, so no line is ruled.
    float y = p.y + (WorldCliffNoise(p * float3(0.035, 0.015, 0.035)) - 0.5) * 2.0 * _StrataWarp
                  + (WorldCliffNoise(p * float3(0.35, 0.2, 0.35) + 3.7) - 0.5) * 0.25 * _StrataSpacing;
    // Beds of uneven height: a slow wave stretches some and squeezes others (it never turns back, so the beds keep their order).
    float spacing = max(_StrataSpacing, 0.05);
    y += sin(y * 0.41 / spacing) * spacing * 0.35;
    float bed = y / spacing;
    float index = floor(bed);
    float within = bed - index;
    float tone = frac(sin(index * 12.9898 + 4.1414) * 43758.5453);
    float hue = frac(sin(index * 78.233 + 1.73) * 43758.5453);
    float worn = frac(sin(index * 39.425 + 8.11) * 43758.5453);
    // Each bed a shade of its own, a little warmer or cooler; broad steps, the way beds read from far off.
    half shade = lerp(1.0 - _StrataStrength, 1.0 + _StrataStrength * 0.45, tone);
    half3 tint = lerp(half3(1.05, 1.0, 0.92), half3(0.94, 0.98, 1.05), hue);
    // Under each bed's lip a soft recess in shadow, as deep as the bed is worn (some hardly at all); just above it the lip catches the light.
    half width = lerp(0.12, 0.3, worn);
    half recess = smoothstep(1.0 - width, 1.0, within) * lerp(0.35, 1.0, worn) * _StrataSeam;
    half lip = (1.0 - smoothstep(0.0, 0.12, within)) * _StrataSeam * 0.35;
    half3 bedColour = tint * shade * (1.0 - recess * 0.6) * (1.0 + lip);
    colour *= lerp(half3(1, 1, 1), bedColour, face);
    mask.g *= lerp(1.0, 1.0 - recess * 0.45, face); // the recess holds shadow
}

// Rock on steep ground: rocky ground (the Rock textures) and, on the steepest, cliff rock (the Cliff Rock textures).
// Where it goes comes from WorldRock: the painted Rocky and Cliff layers (Rock From Painted Layers, so painting another
// ground over them replaces them), or the slope, with a noisy edge either way.
void WorldCliffs(Varyings IN, inout InputData inputData, inout half3 albedo, inout half smoothness, inout half metallic, inout half occlusion)
{
    if (_CliffStrength <= 0)
    {
        return;
    }

    half3 n = WorldGeometricNormal(IN);
    float slope = degrees(acos(saturate(n.y)));
    float3 p = IN.positionWS;
    float noise = WorldCliffNoise(p * 0.35) * 0.65 + WorldCliffNoise(p * 1.1 + 7.3) * 0.35 - 0.5;
    float2 rock = WorldRock(IN.uvMainAndLM.xy, slope + noise * _CliffBreakup * 26.0);
    half w = rock.x;
    if (_RockFromLayers > 0.5)
    {
        w = saturate(w + noise * _CliffBreakup * 2.0 * w * (1.0 - w)); // a ragged edge where the paint fades
    }

    if (w <= 0.001)
    {
        return;
    }

    half3 blend = pow(abs(n), 4.0);
    blend /= max(dot(blend, 1.0), 1e-4);
    half steep = rock.y;
    half3 colour = 0;
    half4 mask = 0;
    half3 rockNormal = n;
    if (steep < 0.999)
    {
        WorldTriplanarRock(TEXTURE2D_ARGS(_CliffAlbedo, sampler_CliffAlbedo), TEXTURE2D_ARGS(_CliffNormal, sampler_CliffAlbedo),
                           TEXTURE2D_ARGS(_CliffMask, sampler_CliffAlbedo), p, n, blend, _CliffTiling, _CliffTint.rgb,
                           _CliffNormalStrength, colour, mask, rockNormal);
    }

    if (steep > 0.001)
    {
        half3 steepColour;
        half4 steepMask;
        half3 steepNormal;
        WorldTriplanarRock(TEXTURE2D_ARGS(_SteepAlbedo, sampler_CliffAlbedo), TEXTURE2D_ARGS(_SteepNormal, sampler_CliffAlbedo),
                           TEXTURE2D_ARGS(_SteepMask, sampler_CliffAlbedo), p, n, blend, _SteepTiling, _SteepTint.rgb,
                           _SteepNormalStrength, steepColour, steepMask, steepNormal);
        bool only = steep >= 0.999;
        colour = only ? steepColour : lerp(colour, steepColour, steep);
        mask = only ? steepMask : lerp(mask, steepMask, steep);
        rockNormal = only ? steepNormal : normalize(lerp(rockNormal, steepNormal, steep));
    }

    WorldStrata(p, slope, colour, mask);
    albedo = lerp(albedo, colour, w);
    metallic = lerp(metallic, mask.r, w);
    occlusion = lerp(occlusion, mask.g, w);
    smoothness = lerp(smoothness, mask.a, w);
    inputData.normalWS = normalize(lerp(inputData.normalWS, rockNormal, w));
}

// Rain on the ground (WeatherSystem sets the wetness). Soaked ground is darker and shinier everywhere it is level enough
// to hold water; puddles fill in the low spots of a noise that stays put, growing with the wetness, and ring under the rain.
float _SafeHavenWetness, _SafeHavenRain;

float WorldWetHash(float2 p)
{
    p = frac(p * float2(123.34, 456.21));
    p += dot(p, p + 45.32);
    return frac(p.x * p.y);
}

float WorldWetNoise(float2 p)
{
    float2 cell = floor(p);
    float2 f = frac(p);
    f = f * f * (3.0 - 2.0 * f);
    return lerp(lerp(WorldWetHash(cell), WorldWetHash(cell + float2(1, 0)), f.x),
                lerp(WorldWetHash(cell + float2(0, 1)), WorldWetHash(cell + float2(1, 1)), f.x), f.y);
}

// How much a raindrop's ring leans the surface here: expanding rings, one to a cell, each with its own moment.
float2 WorldRainRings(float2 p, float time)
{
    float2 cell = floor(p);
    float2 offset = frac(p) - 0.5;
    float seed = WorldWetHash(cell);
    float age = frac(time * 0.9 + seed);
    offset -= (float2(seed, frac(seed * 7.13)) - 0.5) * 0.4;
    float radius = length(offset);
    float wave = sin((radius - age * 0.45) * 42.0) * saturate(1.0 - abs(radius - age * 0.45) * 9.0) * (1.0 - age);
    return radius > 0.001 ? offset / radius * wave : 0;
}

void WorldWetness(Varyings IN, inout InputData inputData, inout half3 albedo, inout half smoothness, inout half metallic, inout half occlusion, out half skySheen)
{
    skySheen = 0;
    half wetness = _SafeHavenWetness;
    if (wetness <= 0.001)
    {
        return;
    }

    // Wide on purpose: terrain normals change from triangle to triangle, and a narrow range draws those triangles.
    half level = smoothstep(0.62, 0.8, WorldGeometricNormal(IN).y);
    half soaked = wetness * (0.5 + 0.5 * level);
    albedo *= 1.0 - 0.34 * soaked;
    smoothness = lerp(smoothness, max(smoothness, 0.62), soaked);

    float2 xz = IN.positionWS.xz;
    float lows = WorldWetNoise(xz * 0.75) * 0.55 + WorldWetNoise(xz * 2.1 + 17.3) * 0.3 + WorldWetNoise(xz * 5.3 + 41.7) * 0.15;
    float shore = lerp(0.76, 0.63, wetness);
    half puddle = smoothstep(shore, shore + 0.05, lows) * level * saturate(wetness * 3.0);
    if (puddle <= 0.001)
    {
        return;
    }

    // Water over a dark bed: from above most of what shows is the mud under it, with the world's reflection (the probe
    // that follows the player) brightening towards the flat angles.
    albedo = lerp(albedo, albedo * 0.45, puddle);
    smoothness = lerp(smoothness, 0.97, puddle);
    metallic = lerp(metallic, 0.06, puddle);
    occlusion = lerp(occlusion, 1.0, puddle);
    float2 lean = _SafeHavenRain * (WorldRainRings(xz * 1.9, _Time.y) + WorldRainRings(xz * 1.9 + 3.7, _Time.y * 1.3 + 0.5)) * 0.32;
    inputData.normalWS = normalize(lerp(inputData.normalWS, normalize(half3(lean.x, 1.0, lean.y)), puddle));

    // A little of the sky's ambient colour on top, so a puddle under an even grey sky never reads as a hole.
    half facing = saturate(dot(inputData.normalWS, inputData.viewDirectionWS));
    skySheen = puddle * lerp(0.1, 0.015, facing * facing);
}

// Frost on the ground in the cold of the year (Seasons sets _SafeHavenSeason.w: how much of the ground is frosted, 0-1;
// x-z are the leaves' and grass's autumn, leaf fall and frost). Level ground frosts first, in patches that spread until
// they nearly meet; slopes keep their colour longer, footprints break it, and a light frost lingers in shade (tree and
// house shadows) after the sun has taken it off the open ground. Hoarfrost, not snow: a mottled, silvery dusting whose
// brightness follows the ground's own texture, so roots, stones and paths still read from the top-down camera.
float4 _SafeHavenSeason;

void WorldFrost(Varyings IN, inout half3 albedo, inout half smoothness)
{
    half amount = _SafeHavenSeason.w;
    if (amount <= 0.001)
    {
        return;
    }

    float2 xz = IN.positionWS.xz;
    half sunlit = MainLightRealtimeShadow(TransformWorldToShadowCoord(IN.positionWS));
    amount *= 1.0 - 0.6 * sunlit * saturate(1.0 - _SafeHavenSeason.z);
    half level = smoothstep(0.5, 0.85, WorldGeometricNormal(IN).y);
    float patches = WorldWetNoise(xz * 0.21 + 63.1) * 0.6 + WorldWetNoise(xz * 0.9 + 11.7) * 0.3 + WorldWetNoise(xz * 3.7 + 5.3) * 0.1;
    patches = saturate((patches - 0.5) * 2.2 + 0.5);
    half cover = smoothstep(0.0, 0.3, amount * 0.9 * lerp(0.45, 1.0, level) - (1.0 - patches) * 0.9);
    cover *= 1.0 - saturate(WorldFootprintMask(xz) * 3.0);
    if (cover <= 0.001)
    {
        return;
    }

    half ground = saturate(dot(albedo, half3(0.3, 0.59, 0.11)) * 2.4);
    half grain = WorldWetNoise(xz * 23.0) * 0.6 + WorldWetNoise(xz * 61.0 + 7.1) * 0.4;
    half crystals = saturate(grain * 1.6 - 0.3);
    half3 frost = half3(0.62, 0.67, 0.74) * (0.5 + 0.6 * ground);
    albedo = lerp(albedo, frost, cover * (0.3 + 0.3 * crystals));
    smoothness = lerp(smoothness, 0.38, cover * 0.7);
}

// Snow lying on the ground (WeatherSystem sets _SafeHavenSnow, 0-1: a winter's thin layer, deeper while it snows). It
// lies where the ground is level enough, shallowest at patches' edges, and footprints and trampling show the ground
// through, so tracks read from above. Puddles have frozen or gone under it (the weather dries the ground while it snows).
float _SafeHavenSnow;

void WorldSnow(Varyings IN, inout InputData inputData, inout half3 albedo, inout half smoothness, inout half metallic, inout half occlusion)
{
    half amount = _SafeHavenSnow;
    if (amount <= 0.001)
    {
        return;
    }

    float2 xz = IN.positionWS.xz;
    half3 geometric = WorldGeometricNormal(IN);
    half level = smoothstep(0.5, 0.85, geometric.y);
    float patches = WorldWetNoise(xz * 0.21 + 63.1) * 0.6 + WorldWetNoise(xz * 0.9 + 11.7) * 0.3 + WorldWetNoise(xz * 3.7 + 5.3) * 0.1;
    half cover = smoothstep(0.0, 0.25, amount * 1.25 * lerp(0.45, 1.0, level) - (1.0 - patches) * 0.9);
    cover *= 1.0 - saturate(WorldFootprintMask(xz) * 3.0);
    if (cover <= 0.001)
    {
        return;
    }

    half ground = saturate(dot(albedo, half3(0.3, 0.59, 0.11)) * 2.4);
    half grain = WorldWetNoise(xz * 23.0) * 0.6 + WorldWetNoise(xz * 61.0 + 7.1) * 0.4;
    half3 snow = half3(0.78, 0.82, 0.89) * (0.66 + 0.34 * ground) * (0.92 + 0.16 * grain);
    albedo = lerp(albedo, snow, cover * 0.9);
    smoothness = lerp(smoothness, 0.3, cover);
    metallic *= 1.0 - cover;
    occlusion = lerp(occlusion, 1.0, cover * 0.6);
    // A layer of snow softens the ground's small relief.
    inputData.normalWS = normalize(lerp(inputData.normalWS, geometric, cover * 0.5));
}
// ---------------------------------------------------------------------------------------------------------------------
"""

