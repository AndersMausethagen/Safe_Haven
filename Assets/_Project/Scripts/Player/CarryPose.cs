/// <summary>
/// An object carried on the shoulder, shown by masking a pose onto one arm.
/// The numbers are written to the Animator's "Carry" parameter, so never renumber a value.
/// </summary>
public enum CarryPose
{
    None = 0,
    ShoulderLeft = 1,
    ShoulderRight = 2,
    ShoulderLeftAlt = 3,
    ShoulderRightAlt = 4,
}
